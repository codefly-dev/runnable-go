// Files of the generated invocation harness.
const (
	// HarnessFile carries the harness, beside the bindings and the handler it
	// runs. It is in the author's own package rather than a subpackage so the
	// invocation identity can reach the handler through its context without an
	// exported setter the author could call by mistake.
	HarnessFile = "harness.go"
	// CommandDirectory holds the executable that serves the runnable. The Go tool
	// ignores a directory whose name begins with a dot or an underscore, so
	// this one cannot be spelled the way the Python agent spells its generated
	// directory.
	CommandDirectory = "codefly"
	// CommandFile is that executable's main package.
	CommandFile = "main.go"
)

// Harness renders the invocation harness of a runnable: the served routes, the
// payload validation the bindings do not do, and the call lifecycle a caller
// observes.
//
// Every fact the harness enforces is rendered into it rather than read at
// runtime from a document beside it. A Go runnable is compiled, so a contract
// carried in a file could be edited after the build that measured it while the
// binary went on honoring the edit; compiled in, the bounds and the release
// identity are covered by the digest of the artifact that carries them.
//
// identity is the release the workspace resolved. Standalone generation has no
// owning workspace and passes nil, which leaves the workspace unchecked at
// invocation time — the same allowance the Python agent makes, because there is
// no resolved workspace to check against.
func Harness(pkg string, runnable *resources.Runnable, identity *basev0.RunnableIdentity) ([]byte, error) {
	if err := validatePackageName(pkg); err != nil {
		return nil, err
	}
	if err := runnable.Contract.Validate(); err != nil {
		return nil, err
	}
	if err := runnable.Execution.Validate(); err != nil {
		return nil, err
	}
	release := runnable.Identity()
	name, module, workspace, version := release.Name, release.Module, "", runnable.Version
	if identity != nil {
		name, module, workspace, version = identity.GetName(), identity.GetModule(), identity.GetWorkspace(), identity.GetVersion()
	}

	var b strings.Builder
	fmt.Fprintf(&b, "//go:build %s\n\n", GoRequirement)
	b.WriteString("// Code generated by runnable-go. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString(harnessImports)

	b.WriteString("\n// The framing this harness implements, and the bounds and policies its\n")
	b.WriteString("// declaration sets. They are constants so the binary cannot be pointed at a\n")
	b.WriteString("// contract other than the one the build measured.\nconst (\n")
	fmt.Fprintf(&b, "\tharnessProtocol = %q\n", resources.RunnableServedProtocolV1)
	fmt.Fprintf(&b, "\tharnessMaxInputBytes = %d\n", runnable.Execution.MaxInputBytes())
	fmt.Fprintf(&b, "\tharnessMaxOutputBytes = %d\n", runnable.Execution.MaxOutputBytes())
	fmt.Fprintf(&b, "\tharnessRecovery = %q\n", string(runnable.Execution.Recovery))
	fmt.Fprintf(&b, "\tharnessCancellation = %q\n", string(runnable.Execution.Cancellation))
	// The declared timeout bounds one call. It is compiled in for the same
	// reason the bounds are: a caller may shorten it with a deadline header and
	// may never overrule the author with a longer one.
	fmt.Fprintf(&b, "\tharnessDeclaredTimeout = %d * time.Nanosecond\n", runnable.Execution.GetTimeout())
	b.WriteString(")\n")

	b.WriteString("\n// harnessRelease is the release this package implements. An invocation\n")
	b.WriteString("// naming another release is refused rather than run against foreign input,\n")
	b.WriteString("// which is what keeps two installed versions of one runnable apart.\n")
	fmt.Fprintf(&b, "var harnessRelease = Release{Name: %q, Module: %q, Workspace: %q, Version: %q}\n",
		name, module, workspace, version)

	b.WriteString("\n// The declared schemas, enforced against the raw payload before it is\n")
	b.WriteString("// decoded: the bindings carry value types and null states, not required\n")
	b.WriteString("// keys, undeclared keys or the signed 64-bit integer range.\n")
	b.WriteString("var harnessInputSchema = ")
	b.WriteString(renderFields(runnable.Contract.Input.Fields, 0))
	b.WriteString("\n\nvar harnessOutputSchema = ")
	b.WriteString(renderFields(runnable.Contract.Output.Fields, 0))
	b.WriteString("\n")
	b.WriteString(harnessBody)
	// The receipt route is the one place the two shapes of the harness differ.
	// A package whose uncertain outcome is resolved by recomputing has no
	// receipt to serve and no ReceiptOf for the route to call, so rendering it
	// anyway would not compile.
	if runnable.Execution.Recovery == resources.RunnableRecoveryReceipt {
		b.WriteString(harnessReceiptBody)
	} else {
		b.WriteString(harnessNoReceiptBody)
	}
	return format.Source([]byte(b.String()))
}

// Command renders the executable that serves this runnable. It is a separate
// main package because the harness shares the author's package, and a package
// that is imported cannot also be a main.
func Command(pkg string) ([]byte, error) {
	if err := validatePackageName(pkg); err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "//go:build %s\n\n", GoRequirement)
	b.WriteString("// Code generated by runnable-go. DO NOT EDIT.\n\n")
	b.WriteString("// Command codefly serves the runnable's operation.\npackage main\n\n")
	fmt.Fprintf(&b, "import (\n\t\"os\"\n\n\t%q\n)\n\n", pkg)
	fmt.Fprintf(&b, "func main() {\n\tos.Exit(%s.Main())\n}\n", pkg)
	return format.Source([]byte(b.String()))
}

// renderFields renders one schema as a Go literal.
func renderFields(fields []*resources.RunnableField, depth int) string {
	if len(fields) == 0 {
		return "[]harnessField{}"
	}
	pad := strings.Repeat("\t", depth+1)
	var b strings.Builder
	b.WriteString("[]harnessField{\n")
	for _, field := range fields {
		b.WriteString(pad)
		b.WriteString(renderField(field, depth+1))
		b.WriteString(",\n")
	}
	b.WriteString(strings.Repeat("\t", depth))
	b.WriteString("}")
	return b.String()
}

func renderField(field *resources.RunnableField, depth int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "{name: %q, kind: %q", field.Name, string(field.Type))
	if field.Optional {
		b.WriteString(", optional: true")
	}
	if field.Nullable {
		b.WriteString(", nullable: true")
	}
	switch field.Type {
	case resources.RunnableFieldObject:
		b.WriteString(", fields: ")
		b.WriteString(renderFields(field.Fields, depth))
	case resources.RunnableFieldArray:
		b.WriteString(", items: &harnessField")
		b.WriteString(renderField(field.Items, depth))
	}
	b.WriteString("}")
	return b.String()
}

